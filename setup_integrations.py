"""Install reviewed external runtimes. Default invocation only lists the plan.

Windows x64 bootstrap is supported. Skills themselves remain cross-platform.
No credentials, provider URLs, plugin trust decisions or model weights are set.
"""
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parent


def read_lock():
    data = json.loads((ROOT / 'integrations-lock.json').read_text(encoding='utf-8'))
    if data.get('schema_version') != 1:
        raise ValueError('Unsupported integration schema')
    return data


def run(args, **kw):
    print('+', subprocess.list2cmdline([str(a) for a in args]), flush=True)
    subprocess.run([str(a) for a in args], check=True, **kw)


def unpack_verified(url, digest, target):
    """Verify before extracting; reject paths escaping the owned target."""
    target.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='aws-download-') as tmp:
        archive = Path(tmp) / 'download.zip'
        with urllib.request.urlopen(url, timeout=120) as response, archive.open('wb') as out:
            shutil.copyfileobj(response, out)
        if hashlib.sha256(archive.read_bytes()).hexdigest() != digest:
            raise ValueError('Download checksum mismatch: ' + url)
        with zipfile.ZipFile(archive) as z:
            for entry in z.infolist():
                resolved = (target / entry.filename).resolve()
                if not resolved.is_relative_to(target.resolve()):
                    raise ValueError('Archive path escapes destination')
                if (entry.external_attr >> 16) & 0o170000 == 0o120000:
                    raise ValueError('Archive symlink is unsupported')
            z.extractall(target)


def save_environment(home, paths):
    destination = home / 'toolchains/ai-work-skills-env.ps1'
    quoted = ["'" + str(p).replace("'", "''") + "'" for p in paths]
    destination.write_text('# Generated by ai-work-skills; dot-source in PowerShell.\n'
                           '$env:PATH = (@(' + ', '.join(quoted) +
                           ') + @($env:PATH)) -join [IO.Path]::PathSeparator\n', encoding='utf-8')
    print('Environment:', destination)


def local_memory_enabled(home):
    config = home / 'config.toml'
    text = config.read_text(encoding='utf-8') if config.exists() else ''
    section = re.search(r'(?m)^\[plugins\."claude-mem@claude-mem-local"\]\s*\n([^\[]*)', text)
    return bool(section and re.search(r'(?m)^enabled\s*=\s*true\s*(?:#.*)?$', section[1]))


def install_plugin(codex, name, home, env):
    if name == 'claude-mem' and local_memory_enabled(home):
        print('Keeping enabled Claude-Mem official local runtime; skipping duplicate plugin.')
        return
    result = json.loads(subprocess.check_output(
        [codex, 'plugin', 'add', name + '@ai-work-skills', '--json'], env=env, text=True, encoding='utf-8'))
    if name == 'ecc':
        target = Path(result['installedPath']).resolve()
        owned = (home / 'plugins/cache/ai-work-skills/ecc').resolve()
        if not target.is_relative_to(owned) or not (target / 'package-lock.json').is_file():
            raise ValueError('Unexpected ECC installation path or missing dependency lock')
        npm = shutil.which('npm.cmd' if sys.platform == 'win32' else 'npm', path=env.get('PATH'))
        if not npm:
            raise RuntimeError('ECC hooks require Node/npm. Run --install first.')
        run([npm, 'ci', '--omit=dev', '--ignore-scripts', '--no-audit', '--no-fund'], cwd=target, env=env)
    print('Installed plugin:', name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--install', action='store_true', help='Install pinned runtimes and generated GSD skills')
    parser.add_argument('--plugins', action='store_true', help='Install the five pinned native Codex plugins')
    parser.add_argument('--skip-gsd', action='store_true', help='Install GSD CLI but do not change Codex config/hooks')
    parser.add_argument('--user-path', action='store_true', help='Also append managed tool paths to the Windows user PATH')
    args = parser.parse_args()
    lock = read_lock()
    for item in lock['repositories']:
        print(item['repo'], item.get('package', item.get('version', item['ref'][:12])),
              ('plugin=' + item['plugin']) if 'plugin' in item else '')
    if not args.install and not args.plugins:
        print('Preview only. Use --install and/or --plugins to apply.')
        return
    home = Path(os.environ.get('CODEX_HOME', str(Path.home() / '.codex'))).resolve()
    toolchains = home / 'toolchains'
    toolchains.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    node_dir = toolchains / ('node-v' + lock['bootstrap']['node']['version'] + '-win-x64')
    env['PATH'] = os.pathsep.join([str(node_dir), env.get('PATH', '')])
    if args.install:
        if sys.platform != 'win32' or platform.machine().lower() not in ('amd64', 'x86_64'):
            raise SystemExit('Runtime bootstrap supports Windows x64. See docs/INTEGRATIONS.md for other systems.')
        node = lock['bootstrap']['node']
        node_dir = toolchains / ('node-v' + node['version'] + '-win-x64')
        if not (node_dir / 'node.exe').is_file():
            unpack_verified(node['url'], node['sha256'], toolchains)
        prefix = toolchains / 'ai-work-skills-npm'
        prefix.mkdir(exist_ok=True)
        env['PATH'] = os.pathsep.join([str(node_dir), str(prefix / 'node_modules/.bin'), env.get('PATH', '')])
        for filename in ('package.json', 'package-lock.json'):
            shutil.copy2(ROOT / 'tools/npm' / filename, prefix / filename)
        # npm.cmd must be launched through cmd on Windows. All arguments here
        # are repository-owned package paths, not arbitrary user shell strings.
        run([node_dir / 'npm.cmd', 'ci', '--prefix', prefix, '--ignore-scripts', '--no-audit', '--no-fund'], env=env)
        for path in ('agent-browser/scripts/postinstall.js', 'esbuild/install.js'):
            run([node_dir / 'node.exe', prefix / 'node_modules' / path], env=env)
        bootstrap = toolchains / 'ai-work-skills-bootstrap'
        bootstrap_python = bootstrap / 'Scripts/python.exe'
        if not bootstrap_python.is_file():
            run([sys.executable, '-m', 'venv', bootstrap])
        run([bootstrap_python, '-m', 'pip', 'install', 'uv==' + lock['bootstrap']['uv']])
        uv = bootstrap / 'Scripts/uv.exe'
        python_version = lock['bootstrap']['python']
        # uv resolves the exact version, avoiding a stale minor-version alias.
        for item in lock['repositories']:
            if item['kind'] == 'python':
                run([uv, 'tool', 'install', '--python', python_version, item['package']], env=env)
        binary_dir = Path(subprocess.check_output([str(uv), 'tool', 'dir', '--bin'], text=True).strip())
        ff = lock['bootstrap']['ffmpeg']
        ff_bin = toolchains / ('ffmpeg-' + ff['version'] + '-essentials_build') / 'bin'
        if not (ff_bin / 'ffmpeg.exe').is_file():
            unpack_verified(ff['url'], ff['sha256'], toolchains)
        bun = lock['bootstrap']['bun']
        bun_root = toolchains / ('bun-' + bun['version'])
        bun_bin = bun_root / 'bun-windows-x64'
        if not (bun_bin / 'bun.exe').is_file():
            unpack_verified(bun['url'], bun['sha256'], bun_root)
        paths = [node_dir, prefix / 'node_modules/.bin', binary_dir, ff_bin, bootstrap / 'Scripts', bun_bin]
        env['PATH'] = os.pathsep.join([*(str(p) for p in paths), env.get('PATH', '')])
        save_environment(home, paths)
        if args.user_path:
            import winreg
            with winreg.CreateKey(winreg.HKEY_CURRENT_USER, 'Environment') as key:
                try:
                    old_path, value_type = winreg.QueryValueEx(key, 'Path')
                except FileNotFoundError:
                    old_path, value_type = '', winreg.REG_EXPAND_SZ
                backup_file = toolchains / 'user-path-before-ai-work-skills.json'
                if not backup_file.exists():
                    backup_file.write_text(json.dumps({'Path': old_path, 'type': value_type}), encoding='utf-8')
                entries = old_path.split(';') if old_path else []
                existing = {os.path.normcase(os.path.normpath(p)) for p in entries}
                for path in paths:
                    if os.path.normcase(os.path.normpath(str(path))) not in existing:
                        entries.append(str(path))
                winreg.SetValueEx(key, 'Path', 0, value_type, ';'.join(entries))
            print('User PATH updated; existing applications must be restarted.')
        if not args.skip_gsd:
            stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
            backup = home / 'integration-backups' / stamp
            backup.mkdir(parents=True)
            for filename in ('config.toml', 'hooks.json', 'AGENTS.md', 'gsd-file-manifest.json'):
                if (home / filename).is_file():
                    shutil.copy2(home / filename, backup / filename)
            for dirname in ('agents', 'hooks'):
                if (home / dirname).is_dir():
                    shutil.copytree(home / dirname, backup / dirname)
            run([prefix / 'node_modules/.bin/gsd-core.cmd', '--codex', '--global'], env=env)
            print('GSD config/agents/hooks backup:', backup)
        run([ff_bin / 'ffmpeg.exe', '-version'], env=env)
        run([binary_dir / 'headroom.exe', '--version'], env=env)
        run([binary_dir / 'yt-dlp.exe', '--version'], env=env)
    if args.plugins:
        codex = shutil.which('codex', path=env.get('PATH'))
        if not codex:
            raise SystemExit('Codex CLI with plugin support must be installed first.')
        # Scope long path support to these Git child processes, preserving global config.
        count = int(env.get('GIT_CONFIG_COUNT', '0'))
        env.update({f'GIT_CONFIG_KEY_{count}': 'core.longpaths', f'GIT_CONFIG_VALUE_{count}': 'true',
                    'GIT_CONFIG_COUNT': str(count + 1)})
        run([codex, 'plugin', 'marketplace', 'add', str(ROOT), '--json'], env=env)
        marketplace = json.loads((ROOT / '.agents/plugins/marketplace.json').read_text(encoding='utf-8'))
        for plugin in marketplace['plugins']:
            install_plugin(codex, plugin['name'], home, env)
    print('Installation finished. Reopen Codex and load the generated environment for CLI tools.')
    print('Account login, plugin hook trust, proxy routing and Whisper model downloads remain separate.')


if __name__ == '__main__':
    main()
